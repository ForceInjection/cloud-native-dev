#!/bin/bash

echo "=== Kubernetes 集群架构 ==="

echo "🎛️ 控制平面组件（Master Node）："
echo "├── kube-apiserver           # API 服务器，集群的前端"
echo "├── etcd                     # 分布式键值存储，保存集群状态"
echo "├── kube-scheduler           # 调度器，决定 Pod 运行在哪个节点"
echo "├── kube-controller-manager  # 控制器管理器，维护集群状态"
echo "└── cloud-controller-manager # 云控制器管理器（可选）"

echo "\n🔧 工作节点组件（Worker Node）："
echo "├── kubelet                  # 节点代理，管理 Pod 生命周期"
echo "├── kube-proxy               # 网络代理，实现服务负载均衡"
echo "├── container-runtime        # 容器运行时（Docker、containerd 等）"
echo "└── Pod                      # 最小部署单元，包含一个或多个容器"

echo "\n=== 核心概念详解 ==="

echo "\n🫘 Pod（豆荚）："
echo "  📝 定义：Kubernetes 中最小的部署单元"
echo "  🔗 特性："
echo "    - 包含一个或多个紧密相关的容器"
echo "    - 共享网络和存储"
echo "    - 同一 Pod 内的容器可以通过 localhost 通信"
echo "    - 拥有唯一的 IP 地址"
echo "    - 生命周期一致（一起创建、一起销毁）"
echo "  💡 使用场景："
echo "    - 主容器 + 辅助容器（sidecar 模式）"
echo "    - 需要共享文件系统的容器组"
echo "    - 需要本地通信的微服务"

echo "\n🌐 Service（服务）："
echo "  📝 定义：为一组 Pod 提供稳定的网络端点"
echo "  🔗 功能："
echo "    - 实现负载均衡和服务发现"
echo "    - 提供稳定的 DNS 名称"
echo "    - 抽象底层 Pod 的变化"
echo "  📋 类型："
echo "    - ClusterIP：集群内部访问（默认）"
echo "    - NodePort：通过节点端口暴露"
echo "    - LoadBalancer：云负载均衡器"
echo "    - ExternalName：DNS 别名"

echo "\n🚀 Deployment（部署）："
echo "  📝 定义：管理 Pod 的副本数量和更新策略"
echo "  🔗 功能："
echo "    - 管理 ReplicaSet"
echo "    - 支持滚动更新和回滚"
echo "    - 确保应用的高可用性"
echo "    - 声明式配置"
echo "  💡 优势："
echo "    - 自动故障恢复"
echo "    - 零停机更新"
echo "    - 版本管理"

echo "\n📁 Namespace（命名空间）："
echo "  📝 定义：提供资源隔离的虚拟集群"
echo "  🔗 功能："
echo "    - 支持多租户环境"
echo "    - 资源配额管理"
echo "    - 访问控制"
echo "  📋 默认命名空间："
echo "    - default：默认命名空间"
echo "    - kube-system：系统组件"
echo "    - kube-public：公共资源"
echo "    - kube-node-lease：节点心跳"

echo "\n=== 资源关系图 ==="
