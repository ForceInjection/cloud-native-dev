echo "\n=== 网络模型 ==="
echo "\n🌐 Kubernetes 网络要求："
echo "  1. 每个 Pod 都有唯一的 IP 地址"
echo "  2. Pod 之间可以直接通信（无需 NAT）"
echo "  3. 节点和 Pod 之间可以直接通信"
echo "  4. Pod 看到的自己的 IP 就是其他 Pod 看到的 IP"

echo "\n🔌 网络组件："
echo "  - CNI (Container Network Interface)：网络插件接口"
echo "  - kube-proxy：实现 Service 的负载均衡"
echo "  - CoreDNS：集群内 DNS 服务"
echo "  - Ingress Controller：HTTP/HTTPS 路由"

echo "\n📋 常用 CNI 插件："
echo "  - Flannel：简单的覆盖网络"
echo "  - Calico：支持网络策略的解决方案"
echo "  - Weave：易于安装和使用"
echo "  - Cilium：基于 eBPF 的高性能网络"

echo "\n=== 存储模型 ==="
echo "\n💾 存储类型："
